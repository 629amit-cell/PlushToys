#!/usr/bin/env python3
"""Create card and thumbnail versions of the aligned product galleries.

Run from the repository root:

    python3 scripts/generate-product-assets.py

The source of truth is catalog-gallery.js. Every product gets a 480 x 480
catalog-card image, and every gallery image gets a 240 x 240 thumbnail. Both
sets stay on the same cream canvas as the 900 x 900 gallery so the product
remains centred and the visual margins stay consistent. Images are written as
WebP for smaller downloads on the live site.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
GALLERY_JS = ROOT / "catalog-gallery.js"
GALLERY_DIR = ROOT / "assets" / "products" / "gallery"
CARDS_DIR = ROOT / "assets" / "products" / "cards"
THUMBS_DIR = ROOT / "assets" / "products" / "thumbs"
CARDS_JS = ROOT / "catalog-cards.js"


def read_gallery() -> dict[str, list[str]]:
    text = GALLERY_JS.read_text(encoding="utf-8")
    pattern = re.compile(r'^\s*"([^"]+)":\s*\[(.*?)\],?\s*$', re.MULTILINE)
    gallery: dict[str, list[str]] = {}
    for match in pattern.finditer(text):
        product_id = match.group(1)
        images = re.findall(r'"([^"]+)"', match.group(2))
        if images:
            gallery[product_id] = images
    return gallery


def resize_image(source: Path, destination: Path, size: int, quality: int) -> None:
    with Image.open(source) as image:
        image = image.convert("RGB")
        image = image.resize((size, size), Image.Resampling.LANCZOS)
        destination.parent.mkdir(parents=True, exist_ok=True)
        image.save(
            destination,
            format="WEBP",
            quality=quality,
            method=6,
        )


def main() -> None:
    gallery = read_gallery()
    if not gallery:
        raise SystemExit("No gallery entries found in catalog-gallery.js")

    CARDS_DIR.mkdir(parents=True, exist_ok=True)
    THUMBS_DIR.mkdir(parents=True, exist_ok=True)

    card_lines = [
        "// Generated by scripts/generate-product-assets.py. Do not edit by hand.",
        "window.PlushStoryCardImages = Object.freeze({",
    ]
    image_count = 0
    card_count = 0
    missing: list[str] = []

    for product_id in sorted(gallery, key=str.lower):
        images = gallery[product_id]
        for image in images:
            source = ROOT / image
            if not source.exists():
                missing.append(image)
                continue
            thumbnail = THUMBS_DIR / source.name
            resize_image(source, thumbnail, 240, 78)
            image_count += 1

        main_image = ROOT / images[0]
        if not main_image.exists():
            continue
        card = CARDS_DIR / f"{product_id}.webp"
        resize_image(main_image, card, 480, 80)
        card_count += 1
        card_lines.append(
            f"  {json.dumps(product_id)}: "
            f"{json.dumps(f'assets/products/cards/{product_id}.webp?v=2')},"
        )

    card_lines.append("});")
    CARDS_JS.write_text("\n".join(card_lines) + "\n", encoding="utf-8")

    for folder in (CARDS_DIR, THUMBS_DIR):
        for stale in folder.glob("*.jpg"):
            stale.unlink()

    total_bytes = sum(path.stat().st_size for path in CARDS_DIR.glob("*.webp"))
    total_bytes += sum(path.stat().st_size for path in THUMBS_DIR.glob("*.webp"))
    print(f"Products: {len(gallery)}")
    print(f"Card images: {card_count}")
    print(f"Gallery thumbnails: {image_count}")
    print(f"New image bytes: {total_bytes:,}")
    if missing:
        print(f"Missing source images: {len(missing)}")
        for image in missing[:20]:
            print(f"  - {image}")


if __name__ == "__main__":
    main()
