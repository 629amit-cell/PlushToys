import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const catalogFiles = [
  "catalog-additions.js",
  "catalog-expansion.js",
  "catalog-amazon.js",
  "catalog-gallery.js",
  "store.js",
];

const sandbox = {
  console,
  Intl,
  Map,
  Set,
  URL,
  window: {
    location: { href: "https://plushstory.example/" },
  },
};
sandbox.globalThis = sandbox;
vm.createContext(sandbox);

for (const file of catalogFiles) {
  const source = fs.readFileSync(path.join(root, file), "utf8");
  vm.runInContext(source, sandbox, { filename: file });
}

const store = sandbox.window.PlushStoryStore;
if (!store || !Array.isArray(store.products)) {
  throw new Error("Could not load the client product catalog.");
}

const catalog = {};
for (const product of store.products) {
  const prices = {};
  for (const size of store.productSizesFor(product)) {
    prices[size] = store.productPrice(product, size);
  }
  catalog[product.id] = {
    id: product.id,
    name: product.name,
    description: product.description,
    caption: product.caption,
    primaryImage: store.productImages(product)[0],
    prices,
  };
}

const output = `// Generated by scripts/generate-server-catalog.mjs. Do not edit by hand.\n// Prices are retail prices in whole Indian rupees.\nexport const CATALOG = Object.freeze(${JSON.stringify(catalog, null, 2)});\n`;

const destination = path.join(root, "functions", "_lib", "catalog-data.js");
fs.mkdirSync(path.dirname(destination), { recursive: true });
fs.writeFileSync(destination, output, "utf8");

console.log(`Wrote ${Object.keys(catalog).length} products to functions/_lib/catalog-data.js`);
